public class Soal8 {

    public void jalankan() {
        System.out.println("=== Soal 8: Perulangan foreach pada Array ===");

        int[] angka = {10, 20, 30, 40, 50};

        System.out.println("Isi array angka:");
        for (int nilai : angka) {
            System.out.println(nilai);
        }
    }
}
